import { expect,it,vi } from 'vitest';
it('keeps background requests tracked without foreground spinner and still reports failures',async()=>{
 vi.resetModules();
 let resolve;
 const fetch=vi.fn(()=>new Promise(r=>{resolve=r;}));
 vi.stubGlobal('window',{fetch,location:{origin:'https://example.test'}});
 const {installHttpActivityTracking,useHttpActivity,HTTP_BACKGROUND}=await import('../src/composables/useHttpActivity.js');
 installHttpActivityTracking();
 const activity=useHttpActivity();
 const request=window.fetch('https://example.test/status',{[HTTP_BACKGROUND]:true});
 expect(activity.isActive.value).toBe(false);
 expect(activity.backgroundLabels.value).toHaveLength(1);
 expect(fetch.mock.calls[0][1][HTTP_BACKGROUND]).toBeUndefined();
 resolve(new Response(JSON.stringify({error:'status unavailable'}),{status:503}));
 await request;
 expect(activity.backgroundLabels.value).toHaveLength(0);
 expect(activity.errors.some(e=>e.message==='status unavailable')).toBe(true);
 const foreground=window.fetch('https://example.test/status');
 expect(activity.isActive.value).toBe(true);
 resolve(new Response('{}'));
 await foreground;
 expect(activity.isActive.value).toBe(false);
 const watcher=window.fetch('https://example.test/functions/v1/setup2-notification-watch',{method:'GET'});
 expect(activity.isActive.value).toBe(false);
 expect(activity.backgroundLabels.value).toHaveLength(1);
 resolve(new Response('{}'));
 await watcher;
 vi.unstubAllGlobals();
});
