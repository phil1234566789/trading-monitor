import {PGlite} from 'npm:@electric-sql/pglite@0.3.14';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec(`
create role anon;create role authenticated;create role service_role bypassrls;
create table mt5_accounts(id uuid primary key,server text,mode text);
create table mt5_history_sync(account_id uuid primary key,in_progress boolean,last_error text,last_full_at timestamptz,synced_at timestamptz);
create table dealing_ranges(id bigint primary key,instrument text,direction text);
create table trade_positions(id bigint generated always as identity primary key,dealing_range_id bigint references dealing_ranges(id) on delete cascade,
 source text,entry_price numeric,stop_loss numeric,exit_price numeric,triggered_at timestamptz,exit_time timestamptz,size numeric,net_pl numeric,commission numeric,outcome text,r_multiple numeric,trading_account_id bigint);
alter table trade_positions enable row level security;
create policy old_public_policy on trade_positions for all to anon using(true) with check(true);
grant all on trade_positions,dealing_ranges,mt5_accounts,mt5_history_sync to service_role,anon,authenticated;
grant usage,select on all sequences in schema public to service_role,anon;
insert into mt5_accounts values('11111111-1111-4111-8111-111111111111','Demo-Server','demo');
insert into mt5_history_sync values('11111111-1111-4111-8111-111111111111',false,null,'2026-10-31T12:00:00Z','2026-10-31T12:00:00Z');
insert into dealing_ranges values(1,'XAUUSD','long'),(2,'XAUUSD','long'),(3,'GBPUSD','short');
`);
await db.exec(await Deno.readTextFile(new URL('../supabase/migrations/20261031230000_mt5_journal.sql',import.meta.url)));
const position={entry_price:2300,stop_loss:null,exit_price:2310,triggered_at:'2026-10-31T10:00:00Z',exit_time:'2026-10-31T11:00:00Z',size:.01,net_pl:7.3,commission:-2,outcome:'win',direction:'long',account_currency:'EUR'};
const call=(range=1,broker=23,existing:number|null=null)=>db.query<{id:number}>(`select import_mt5_journal($1,'Demo-Server',$2,$3,'XAUUSD',$4::jsonb,'2026-10-31T12:00:00Z',$5,null) id`,['11111111-1111-4111-8111-111111111111',broker,range,JSON.stringify(position),existing]);
await db.exec('set role service_role');
const first=(await call()).rows[0].id;
assert.equal((await call()).rows[0].id,first);
assert.equal((await db.query('select * from trade_positions')).rows.length,1);
assert.equal((await db.query<{account_currency:string}>('select account_currency from trade_positions')).rows[0].account_currency,'EUR');
await assert.rejects(()=>call(2),/position_already_linked/);
await assert.rejects(()=>call(3,24),/range_mismatch/);
await db.exec('set role anon');
assert.equal((await db.query('select * from trade_positions')).rows.length,0);
assert.equal((await db.query('update trade_positions set broker_private=false returning id')).rows.length,0);
await assert.rejects(()=>db.exec('select * from mt5_journal_links'),/permission denied/);
await assert.rejects(()=>db.exec('select * from trade_journal_comments'),/permission denied/);
await assert.rejects(()=>call(),/permission denied/);
await assert.rejects(()=>db.exec('insert into trade_positions(dealing_range_id,broker_private) values(1,true)'),/row-level security/);
await db.exec(`insert into trade_positions(dealing_range_id,source,stop_loss) values(2,'paper',2290)`);
const publicId=(await db.query<{id:number}>('select id from trade_positions')).rows[0].id;
await db.exec('set role service_role');
await assert.rejects(()=>call(2,24),/existing_position_required/);
assert.equal((await call(2,24,publicId)).rows[0].id,publicId);
await db.exec('update mt5_history_sync set in_progress=true');
await assert.rejects(()=>call(2,25),/broker_history_changed/);
assert.equal(Number((await db.query<{stop_loss:string}>('select stop_loss from trade_positions where id=$1',[publicId])).rows[0].stop_loss),2290);
await db.exec('set role anon');
await assert.rejects(()=>db.exec('delete from dealing_ranges where id=1'),/foreign key/);
await db.exec('set role authenticated');
assert.equal((await db.query('select * from trade_positions')).rows.length,0);
await db.close();
console.log('Migration: retry/conflict, RLS, RPC grants, existing-position reuse and protected cascade passed.');
